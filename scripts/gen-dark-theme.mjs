// Writes src/web/dark.css: the dark theme as a remap of Tailwind's color scales, so components
// keep plain classes (bg-slate-50, text-indigo-700...) and still look right in dark mode.
//   node scripts/gen-dark-theme.mjs          writes the file
//   node scripts/gen-dark-theme.mjs --check  fails if the file is out of date (npm run lint)
// Neutral (slate) is inverted; colored scales become dark tints (50 to 200) and lighter text
// (600 to 950). Things that must keep their contrast use semantic tokens instead (index.css):
// surface (cards), ink and on-ink (dark buttons and toasts), black overlays.
import { readFileSync, writeFileSync } from "node:fs";

const theme = readFileSync("node_modules/tailwindcss/theme.css", "utf8");
const color = (name) => {
  const m = new RegExp(`--color-${name}:\\s*([^;]+);`).exec(theme);
  if (!m) throw new Error(`no color ${name}`);
  return m[1].trim();
};

const BASE = "oklch(17% 0.012 260)"; // page background in dark mode
const FAMILIES = ["indigo", "rose", "amber", "emerald", "sky", "violet", "teal", "orange", "yellow", "red", "green", "blue"];
const mix = (c, pct) => `color-mix(in oklab, ${c} ${pct}%, ${BASE})`;

const lines = [];
const slate = {
  50: BASE,
  100: "oklch(23% 0.014 260)",
  200: "oklch(29% 0.016 260)",
  300: "oklch(36% 0.018 260)",
  400: color("slate-500"),
  500: color("slate-400"),
  600: color("slate-300"),
  700: color("slate-200"),
  800: color("slate-100"),
  900: color("slate-50"),
  950: "#fff",
};
for (const [k, v] of Object.entries(slate)) lines.push(`    --color-slate-${k}: ${v};`);
for (const f of FAMILIES) {
  const map = {
    50: mix(color(`${f}-900`), 30),
    100: mix(color(`${f}-900`), 50),
    200: mix(color(`${f}-700`), 55),
    300: color(`${f}-700`),
    400: color(`${f}-500`),
    500: color(`${f}-400`),
    600: color(`${f}-500`),
    700: color(`${f}-300`),
    800: color(`${f}-200`),
    900: color(`${f}-100`),
    950: color(`${f}-50`),
  };
  for (const [k, v] of Object.entries(map)) lines.push(`    --color-${f}-${k}: ${v};`);
}
const vars = lines.join("\n");
const css = `/* Generated by scripts/gen-dark-theme.mjs: do not edit by hand. */
/* The app follows the system setting (light or dark). */
@media (prefers-color-scheme: dark) {
  :root {
    --color-surface: oklch(21% 0.014 260);
    --color-ink: ${color("slate-100")};
    --color-on-ink: ${color("slate-900")};
${vars}
  }
}
`;
const out = "src/web/dark.css";
if (process.argv.includes("--check")) {
  if (readFileSync(out, "utf8") !== css) {
    console.error(`${out} is out of date: run node scripts/gen-dark-theme.mjs`);
    process.exit(1);
  }
  console.log("dark theme: ok");
} else {
  writeFileSync(out, css);
  console.log(`wrote ${out}`);
}
